let currentLang = "fa";
const toggle = document.getElementById("languageToggle");

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  document.body.classList.toggle("en", lang === "en");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const value = translations[lang][key];
    if (value !== undefined) el.innerHTML = value;
  });

  toggle.textContent = lang === "fa" ? "EN" : "فا";
  toggle.setAttribute("aria-label", lang === "fa" ? "Switch to English" : "تغییر زبان به فارسی");
  document.title = lang === "fa"
    ? "نیلوفر دیونداری | تولید محتوا و تدوین"
    : "Niloofar Divandari | Content Creator & Video Editor";
}

toggle.addEventListener("click", () => setLanguage(currentLang === "fa" ? "en" : "fa"));
document.getElementById("year").textContent = new Date().getFullYear();

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));
} else {
  document.querySelectorAll(".reveal").forEach((el) => el.classList.add("is-visible"));
}

